#!/usr/bin/env python3
"""Generate ASCII G-code for a 10 x 10 x 10 mm solid PLA cube.

Printer-specific startup/shutdown commands and placement are read from one of
Prusa_MK3S.txt, Prusa_MK4.txt, or Prusa_XL.txt in this folder or its parent.

Examples:
    python3 generate_cube_gcode.py Prusa_MK3S.txt
    python3 generate_cube_gcode.py Prusa_MK4.txt --output mk4_cube.gcode
    python3 generate_cube_gcode.py Prusa_XL.txt

Output is ASCII .gcode, including for profiles derived from .bgcode references.
"""

import argparse
import math
from pathlib import Path


def read_profile(path):
    sections = {"settings": [], "header": [], "footer": []}
    section = None
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line in ("[settings]", "[header]", "[footer]"):
            section = line[1:-1]
        elif section is not None:
            sections[section].append(line)
        elif line and not line.startswith("#"):
            raise ValueError(f"{path}:{number}: unexpected text before a section")
    settings = {}
    for line in sections["settings"]:
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise ValueError(f"Bad setting in {path}: {line}")
        key, value = line.split("=", 1)
        settings[key.strip()] = value.strip()
    if not sections["header"] or not sections["footer"]:
        raise ValueError("Profile needs nonempty [header] and [footer] sections")
    header = "\n".join(sections["header"]).strip()
    footer = "\n".join(sections["footer"]).strip()
    for command in ("G90", "M83", "G21", "M862.3"):
        if command not in header:
            raise ValueError(f"Header is missing {command}")
    if "M140 S0" not in footer or "M104" not in footer or "M84" not in footer:
        raise ValueError("Footer must shut down nozzle, bed, and motors")
    return settings, header, footer


def generate(settings, header, footer):
    model = settings["model"]
    if model not in {"MK3S", "MK4", "XL"}:
        raise ValueError(f"Unsupported printer model: {model}")
    size = float(settings["cube_mm"])
    height = float(settings["layer_height_mm"])
    width = float(settings["extrusion_width_mm"])
    filament = float(settings["filament_diameter_mm"])
    x0 = float(settings["x_min"])
    y0 = float(settings["y_min"])
    travel_feed = int(settings["travel_feed_mm_min"])
    initial_retracted = float(settings["initial_retracted_mm"])
    layers = round(size / height)
    if not (size == 10 and height == 0.2 and width == 0.4 and filament == 1.75):
        raise ValueError("These profiles are calibrated for a 10 mm cube, 0.2 mm layers, 0.4 mm bead, and 1.75 mm filament")
    if layers != 50 or not (0 <= initial_retracted <= 2):
        raise ValueError("Invalid layer count or initial retraction")
    if x0 < 0 or y0 < 0:
        raise ValueError("Cube placement must be nonnegative")
    area = math.pi * (filament / 2) ** 2
    extrusion_per_mm = width * height / area
    lines = [
        "; Generated by generate_cube_gcode.py from " + model + " profile",
        "; 10 x 10 x 10 mm solid cube; 50 layers of 0.2 mm; 0.4 mm nozzle; PLA",
        "; Units: mm; absolute XYZ; relative extrusion",
        header,
        "",
        "; Begin generated cube toolpath",
    ]
    x1, y1 = x0 + size, y0 + size
    outer = (x0 + width / 2, y0 + width / 2, x1 - width / 2, y1 - width / 2)
    inner = (x0 + 1.5 * width, y0 + 1.5 * width, x1 - 1.5 * width, y1 - 1.5 * width)
    fill = (x0 + 2.5 * width, y0 + 2.5 * width, x1 - 2.5 * width, y1 - 2.5 * width)
    current = None
    retracted = initial_retracted
    total_extrusion = 0.0

    def travel(x, y):
        nonlocal current
        lines.append(f"G0 X{x:.3f} Y{y:.3f} F{travel_feed}")
        current = (x, y)

    def extrude(x, y):
        nonlocal current, total_extrusion
        distance = math.dist(current, (x, y))
        amount = distance * extrusion_per_mm
        if amount <= 0:
            raise ValueError("Zero-length extrusion move")
        lines.append(f"G1 X{x:.3f} Y{y:.3f} E{amount:.5f} F1200")
        total_extrusion += amount
        current = (x, y)

    def perimeter(box):
        left, bottom, right, top = box
        travel(left, bottom)
        for x, y in ((right, bottom), (right, top), (left, top), (left, bottom)):
            extrude(x, y)

    for layer in range(1, layers + 1):
        z = layer * height
        if layer == 2:
            lines.append(f"M104 S{settings['later_nozzle_c']} ; subsequent layer nozzle temperature")
        if layer in (2, 3, 4):
            fan = int(settings[f"fan_after_layer_{layer - 1}"])
            lines.append(f"M106 S{fan}")
        lines.extend([";LAYER_CHANGE", f";Z:{z:.2f}", f";HEIGHT:{height:.2f}"])
        lines.append(f"G0 Z{z + 0.4:.3f} F720")
        travel(outer[0], outer[1])
        lines.append(f"G0 Z{z:.3f} F720")
        if retracted:
            lines.append(f"G1 E{retracted:.3f} F1500 ; restore retraction")
            retracted = 0.0
        if layer == 1 and model != "MK3S":
            lines.append("M486 S0 ; begin cube object")
        lines.append(";TYPE:Perimeter")
        for box in (outer, inner):
            perimeter(box)
        lines.append(";TYPE:Solid infill")
        low_x, low_y, high_x, high_y = fill
        for index in range(21):
            offset = index * width
            if layer % 2:
                y = low_y + offset
                start_x, end_x = (low_x, high_x) if index % 2 == 0 else (high_x, low_x)
                travel(start_x, y)
                extrude(end_x, y)
            else:
                x = low_x + offset
                start_y, end_y = (low_y, high_y) if index % 2 == 0 else (high_y, low_y)
                travel(x, start_y)
                extrude(x, end_y)
        if layer < layers:
            lines.append("G1 E-0.8 F2100 ; retract for layer travel")
            retracted = 0.8
        progress = min(99, int(layer * 100 / layers))
        lines.append(f"M73 P{progress} R0")
    lines.extend(["; End generated cube toolpath", footer, ""])
    if abs((layers * height) - size) > 1e-9 or total_extrusion <= 0:
        raise ValueError("Generated toolpath failed geometry validation")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profile", type=Path, help="one of the three Prusa_*.txt profile files")
    parser.add_argument("--output", type=Path, help="output ASCII .gcode path")
    args = parser.parse_args()
    profile = args.profile
    if not profile.is_file() and not profile.is_absolute():
        script_dir = Path(__file__).resolve().parent
        for candidate in (script_dir / profile, script_dir.parent / profile):
            if candidate.is_file():
                profile = candidate
                break
    settings, header, footer = read_profile(profile)
    output = args.output or Path(__file__).with_name(f"cube_10mm_generated_{settings['model']}.gcode")
    if output.suffix.lower() != ".gcode":
        parser.error("Output filename must end in .gcode (ASCII G-code)")
    content = generate(settings, header, footer)
    output.write_text(content, encoding="utf-8")
    print(f"Wrote {output} ({settings['model']}, 50 layers, 10 x 10 x 10 mm)")


if __name__ == "__main__":
    main()
